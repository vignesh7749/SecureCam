import React, { useState } from 'react';
import { useSurveillance } from '../../context/SurveillanceContext';
import { Button } from '../common/Button';
import { 
  Printer, 
  FileSpreadsheet, 
  FileCode,
  CheckCircle2,
  FileText
} from 'lucide-react';

export const ReportGenerator: React.FC = () => {
  const { 
    activeSource, 
    modelConfig, 
    zones, 
    trackedObjects,
    allSessionTargets,
    unknownObjects, 
    activeViolations, 
    events,
    totalDurationSeconds,
    totalUniqueTracksCount
  } = useSurveillance();

  const [downloadSuccess, setDownloadSuccess] = useState<string | null>(null);

  // Use full video targets if available, fallback to current frame
  const targetsToUse = allSessionTargets.length > 0 ? allSessionTargets : trackedObjects;
  const uniqueTargetsCount = targetsToUse.length > 0 ? targetsToUse.length : totalUniqueTracksCount;
  const knownTargetsCount = targetsToUse.filter(t => !t.isUnknown).length;
  const totalObjectsCount = targetsToUse.reduce((acc, t) => acc + (t.hits || 1), 0) || targetsToUse.length;
  const formattedDuration = `${String(Math.floor(totalDurationSeconds / 60)).padStart(2, '0')}:${String(Math.floor(totalDurationSeconds % 60)).padStart(2, '0')}`;
  const reportDate = new Date().toLocaleDateString('en-US', { 
    year: 'numeric', 
    month: 'long', 
    day: 'numeric', 
    hour: '2-digit', 
    minute: '2-digit' 
  });

  const formatTimestamp = (val?: string | number) => {
    if (typeof val === 'number') {
      return `${String(Math.floor(val / 60)).padStart(2, '0')}:${String(Math.floor(val % 60)).padStart(2, '0')}`;
    }
    if (!val) return '00:00';
    if (val.includes(':') && val.length <= 8) return val.slice(0, 5);
    if (val.includes('T')) {
      const parts = val.split('T')[1].split(':');
      return `${parts[0] || '00'}:${parts[1] || '00'}`;
    }
    return '00:00';
  };

  const handleExportJson = () => {
    const reportPayload = {
      reportTitle: 'SECURECAM VIDEO ANALYSIS REPORT',
      generatedAt: new Date().toISOString(),
      reportDate,
      videoInformation: {
        video: activeSource.name || 'Testing_1.mp4',
        sourceId: activeSource.id,
        resolution: activeSource.resolution,
        fps: activeSource.fps,
        duration: formattedDuration,
        durationSeconds: totalDurationSeconds,
      },
      analysisSummary: {
        totalObjectsDetected: totalObjectsCount,
        uniqueTargetsTracked: uniqueTargetsCount,
        knownObjects: knownTargetsCount,
        unknownObjects: unknownObjects.length,
        zoneViolations: activeViolations.length,
        totalEvents: events.length,
      },
      detectedObjects: targetsToUse.map(t => ({
        trackId: `#${String(t.trackingId).padStart(2, '0')}`,
        trackingId: t.trackingId,
        class: (t.className || 'OBJECT').toUpperCase(),
        confidence: Number(t.confidence.toFixed(2)),
        confidencePercentage: `${(t.confidence * 100).toFixed(0)}%`,
        status: t.isUnknown ? 'Needs Review' : 'Tracked',
        isUnknown: t.isUnknown,
        firstSeen: formatTimestamp(t.firstSeen),
        lastSeen: formatTimestamp(t.lastSeen),
      })),
      securityEvents: events.map(e => ({
        timestamp: formatTimestamp(e.timestamp),
        event: e.description || e.type,
        target: `${(e.objectClass || 'TARGET').toUpperCase()} #${e.trackingId || 'N/A'}`,
        zone: e.zoneName || 'Emergency Zone',
        severity: e.severity,
      })),
      zoneActivity: zones.map(z => {
        const viols = activeViolations.filter(v => v.zoneName === z.name || v.id.includes(z.id));
        return {
          zoneName: z.name,
          type: z.type.replace('_', ' ').toUpperCase(),
          violationsCount: viols.length,
        };
      }),
      modelDetails: {
        modelName: modelConfig.name,
        backend: modelConfig.backend,
        tracker: modelConfig.tracker,
      },
      footer: 'REPORT GENERATED BY SECURECAM',
    };

    const blob = new Blob([JSON.stringify(reportPayload, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const fileName = `SECURECAM_${(activeSource.name || 'VIDEO').replace(/\s+/g, '_')}_REPORT.json`;
    const a = document.createElement('a');
    a.href = url;
    a.download = fileName;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);

    setDownloadSuccess(fileName);
    setTimeout(() => setDownloadSuccess(null), 3000);
  };

  const handleExportCsv = () => {
    const rows: string[] = [];
    // Standard schema requested: Timestamp,Track ID,Object,Confidence,Status,Zone Event
    rows.push('Timestamp,Track ID,Object,Confidence,Status,Zone Event');

    targetsToUse.forEach(t => {
      const ts = formatTimestamp(t.firstSeen || t.lastSeen);
      const trackId = `#${String(t.trackingId).padStart(2, '0')}`;
      const obj = (t.className || 'OBJECT').toUpperCase();
      const conf = t.confidence.toFixed(2);
      const st = t.isUnknown ? 'Needs Review' : 'Tracked';
      const relatedViol = activeViolations.find(v => v.trackingId === t.trackingId);
      const relatedEvent = events.find(e => e.trackingId === t.trackingId);
      const zoneEvent = t.currentZoneName || relatedViol?.zoneName || relatedEvent?.zoneName || 'None';
      rows.push(`"${ts}","${trackId}","${obj}",${conf},"${st}","${zoneEvent}"`);
    });

    // Also include any security events not strictly matched to an active target
    events.forEach(e => {
      const ts = formatTimestamp(e.timestamp);
      const trackId = e.trackingId ? `#${String(e.trackingId).padStart(2, '0')}` : 'N/A';
      const obj = (e.objectClass || 'TARGET').toUpperCase();
      const conf = '1.00';
      const st = 'Security Alert';
      const zoneEvent = e.zoneName || 'Emergency Zone';
      // Only push if not already accounted for
      if (!targetsToUse.some(t => t.trackingId === e.trackingId && formatTimestamp(t.firstSeen) === ts)) {
        rows.push(`"${ts}","${trackId}","${obj}",${conf},"${st}","${zoneEvent}"`);
      }
    });

    const csvContent = rows.join('\n');
    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const fileName = `SECURECAM_${(activeSource.name || 'VIDEO').replace(/\s+/g, '_')}_DATA.csv`;
    const a = document.createElement('a');
    a.href = url;
    a.download = fileName;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);

    setDownloadSuccess(fileName);
    setTimeout(() => setDownloadSuccess(null), 3000);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="space-y-6">
      {/* Page Heading & Controls (Hidden in Print) */}
      <div className="no-print border-b border-slate-200 dark:border-slate-800 pb-3 flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div>
          <h1 className="text-xl font-bold text-slate-900 dark:text-white tracking-tight">Analysis Reports</h1>
          <p className="text-xs text-slate-500 dark:text-slate-400 mt-0.5">
            Download detected targets, security events, and zone metrics or print a dedicated SecureCam report
          </p>
        </div>

        {/* Action Buttons: DOWNLOAD JSON, DOWNLOAD CSV, PRINT / PDF */}
        <div className="flex flex-wrap sm:flex-nowrap items-center gap-2 w-full sm:w-auto">
          <Button
            variant="outline"
            size="sm"
            className="flex-1 sm:flex-none justify-center"
            onClick={handleExportJson}
            icon={<FileCode className="w-3.5 h-3.5" />}
          >
            Download JSON
          </Button>

          <Button
            variant="outline"
            size="sm"
            className="flex-1 sm:flex-none justify-center"
            onClick={handleExportCsv}
            icon={<FileSpreadsheet className="w-3.5 h-3.5" />}
          >
            Download CSV
          </Button>

          <Button
            variant="primary"
            size="sm"
            className="flex-1 sm:flex-none justify-center"
            onClick={handlePrint}
            icon={<Printer className="w-3.5 h-3.5" />}
          >
            Print / PDF Report
          </Button>
        </div>
      </div>

      {downloadSuccess && (
        <div className="no-print p-3 bg-emerald-500/10 border border-emerald-500/30 rounded text-xs text-emerald-600 dark:text-emerald-300 flex items-center gap-2">
          <CheckCircle2 className="w-4 h-4 text-emerald-500 dark:text-emerald-400" />
          <span>Saved <strong>{downloadSuccess}</strong> to your computer.</span>
        </div>
      )}

      {/* DEDICATED REPORT CONTAINER (Visible on Screen as Preview & Isolated in Print) */}
      <div 
        id="securecam-printable-report" 
        className="bg-white dark:bg-slate-850 border border-slate-200 dark:border-slate-800 rounded-lg p-4 sm:p-8 space-y-6 shadow-xs print:border-none print:shadow-none print:p-0"
      >
        {/* Report Header */}
        <div className="border-b-2 border-slate-900 dark:border-white pb-4">
          <div className="flex items-center justify-between">
            <div>
              <div className="text-xs font-black tracking-widest text-blue-600 dark:text-blue-400 uppercase">
                SECURECAM
              </div>
              <h2 className="text-xl sm:text-2xl font-black text-slate-900 dark:text-white tracking-tight uppercase mt-0.5">
                VIDEO ANALYSIS REPORT
              </h2>
            </div>
            <div className="text-right">
              <span className="inline-block px-2.5 py-1 rounded text-[11px] font-semibold bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300 border border-slate-200 dark:border-slate-700">
                OFFICIAL REPORT
              </span>
            </div>
          </div>
        </div>

        {/* Video Information */}
        <div className="space-y-2">
          <h3 className="text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400 border-b border-slate-200 dark:border-slate-800 pb-1">
            Video Information
          </h3>
          <div className="grid grid-cols-1 sm:grid-cols-3 gap-2.5 text-xs pt-1">
            <div className="p-2.5 rounded bg-slate-50 dark:bg-slate-900 border border-slate-200 dark:border-slate-800">
              <span className="text-slate-500 dark:text-slate-400 text-[11px] block">Video:</span>
              <strong className="text-slate-900 dark:text-white mt-0.5 block truncate">
                {activeSource.name || 'Testing_1.mp4'}
              </strong>
            </div>
            <div className="p-2.5 rounded bg-slate-50 dark:bg-slate-900 border border-slate-200 dark:border-slate-800">
              <span className="text-slate-500 dark:text-slate-400 text-[11px] block">Date:</span>
              <strong className="text-slate-900 dark:text-white mt-0.5 block">
                {reportDate}
              </strong>
            </div>
            <div className="p-2.5 rounded bg-slate-50 dark:bg-slate-900 border border-slate-200 dark:border-slate-800">
              <span className="text-slate-500 dark:text-slate-400 text-[11px] block">Duration:</span>
              <strong className="text-slate-900 dark:text-white font-mono mt-0.5 block">
                {formattedDuration}
              </strong>
            </div>
          </div>
        </div>

        {/* Analysis Summary */}
        <div className="space-y-2">
          <h3 className="text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400 border-b border-slate-200 dark:border-slate-800 pb-1">
            Analysis Summary
          </h3>
          <div className="grid grid-cols-2 sm:grid-cols-3 lg:grid-cols-5 gap-2.5 text-xs pt-1">
            <div className="p-2.5 rounded bg-slate-50 dark:bg-slate-900 border border-slate-200 dark:border-slate-800">
              <span className="text-slate-500 dark:text-slate-400 text-[11px] block">Total Objects Detected</span>
              <span className="text-lg font-black text-slate-900 dark:text-white mt-1 block">{totalObjectsCount}</span>
            </div>
            <div className="p-2.5 rounded bg-slate-50 dark:bg-slate-900 border border-slate-200 dark:border-slate-800">
              <span className="text-slate-500 dark:text-slate-400 text-[11px] block">Unique Targets Tracked</span>
              <span className="text-lg font-black text-emerald-600 dark:text-emerald-400 mt-1 block">{uniqueTargetsCount}</span>
            </div>
            <div className="p-2.5 rounded bg-slate-50 dark:bg-slate-900 border border-slate-200 dark:border-slate-800">
              <span className="text-slate-500 dark:text-slate-400 text-[11px] block">Known Objects</span>
              <span className="text-lg font-black text-blue-600 dark:text-blue-400 mt-1 block">{knownTargetsCount}</span>
            </div>
            <div className="p-2.5 rounded bg-slate-50 dark:bg-slate-900 border border-slate-200 dark:border-slate-800">
              <span className="text-slate-500 dark:text-slate-400 text-[11px] block">Unknown Objects</span>
              <span className="text-lg font-black text-amber-600 dark:text-amber-400 mt-1 block">{unknownObjects.length}</span>
            </div>
            <div className="col-span-2 sm:col-span-1 p-2.5 rounded bg-slate-50 dark:bg-slate-900 border border-slate-200 dark:border-slate-800">
              <span className="text-slate-500 dark:text-slate-400 text-[11px] block">Zone Violations</span>
              <span className="text-lg font-black text-red-600 dark:text-red-400 mt-1 block">{activeViolations.length}</span>
            </div>
          </div>
        </div>

        {/* Detected Objects Table */}
        <div className="space-y-2">
          <h3 className="text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400 border-b border-slate-200 dark:border-slate-800 pb-1">
            Detected Objects
          </h3>
          <div className="border border-slate-200 dark:border-slate-800 rounded overflow-x-auto">
            <table className="w-full text-xs text-left">
              <thead className="bg-slate-100 dark:bg-slate-900 text-slate-700 dark:text-slate-300 font-semibold border-b border-slate-200 dark:border-slate-800">
                <tr>
                  <th className="px-3.5 py-2">ID</th>
                  <th className="px-3.5 py-2">Class</th>
                  <th className="px-3.5 py-2">Confidence</th>
                  <th className="px-3.5 py-2">Status</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
                {targetsToUse.length === 0 ? (
                  <tr>
                    <td colSpan={4} className="px-3.5 py-3 text-center text-slate-500 dark:text-slate-400">
                      No objects detected in the current footage.
                    </td>
                  </tr>
                ) : (
                  targetsToUse.map((t) => (
                    <tr key={t.trackingId} className="hover:bg-slate-50 dark:hover:bg-slate-900/50">
                      <td className="px-3.5 py-2 font-mono font-bold text-slate-900 dark:text-white">
                        #{String(t.trackingId).padStart(2, '0')}
                      </td>
                      <td className="px-3.5 py-2 font-medium text-slate-800 dark:text-slate-200">
                        {(t.className || 'OBJECT').toUpperCase()}
                      </td>
                      <td className="px-3.5 py-2 font-mono text-slate-600 dark:text-slate-400">
                        {(t.confidence * 100).toFixed(1)}%
                      </td>
                      <td className="px-3.5 py-2">
                        {t.isUnknown ? (
                          <span className="px-1.5 py-0.5 rounded text-[10px] font-medium bg-amber-500/15 text-amber-600 dark:text-amber-400 border border-amber-500/30">
                            Needs Review
                          </span>
                        ) : (
                          <span className="px-1.5 py-0.5 rounded text-[10px] font-medium bg-emerald-500/15 text-emerald-600 dark:text-emerald-400 border border-emerald-500/30">
                            Tracked
                          </span>
                        )}
                      </td>
                    </tr>
                  ))
                )}
              </tbody>
            </table>
          </div>
        </div>

        {/* Security Events Table */}
        <div className="space-y-2">
          <h3 className="text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400 border-b border-slate-200 dark:border-slate-800 pb-1">
            Security Events
          </h3>
          <div className="border border-slate-200 dark:border-slate-800 rounded overflow-x-auto">
            <table className="w-full text-xs text-left">
              <thead className="bg-slate-100 dark:bg-slate-900 text-slate-700 dark:text-slate-300 font-semibold border-b border-slate-200 dark:border-slate-800">
                <tr>
                  <th className="px-3.5 py-2">Timestamp</th>
                  <th className="px-3.5 py-2">Event</th>
                  <th className="px-3.5 py-2">Target</th>
                  <th className="px-3.5 py-2">Zone</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
                {events.length === 0 ? (
                  <tr>
                    <td colSpan={4} className="px-3.5 py-3 text-center text-slate-500 dark:text-slate-400">
                      No security violations detected.
                    </td>
                  </tr>
                ) : (
                  events.map((e) => (
                    <tr key={e.id} className="hover:bg-slate-50 dark:hover:bg-slate-900/50">
                      <td className="px-3.5 py-2 font-mono text-slate-600 dark:text-slate-400">
                        {formatTimestamp(e.timestamp)}
                      </td>
                      <td className="px-3.5 py-2 font-medium text-slate-800 dark:text-slate-200">
                        {e.description || e.type}
                      </td>
                      <td className="px-3.5 py-2 text-slate-700 dark:text-slate-300 font-medium">
                        {(e.objectClass || 'TARGET').toUpperCase()} #{e.trackingId || 'N/A'}
                      </td>
                      <td className="px-3.5 py-2 text-slate-600 dark:text-slate-400">
                        {e.zoneName || 'Emergency Zone'}
                      </td>
                    </tr>
                  ))
                )}
              </tbody>
            </table>
          </div>
        </div>

        {/* Zone Activity Table */}
        <div className="space-y-2">
          <h3 className="text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400 border-b border-slate-200 dark:border-slate-800 pb-1">
            Zone Activity
          </h3>
          <div className="border border-slate-200 dark:border-slate-800 rounded overflow-x-auto">
            <table className="w-full text-xs text-left">
              <thead className="bg-slate-100 dark:bg-slate-900 text-slate-700 dark:text-slate-300 font-semibold border-b border-slate-200 dark:border-slate-800">
                <tr>
                  <th className="px-3.5 py-2">Zone Name</th>
                  <th className="px-3.5 py-2">Type</th>
                  <th className="px-3.5 py-2">Violations</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
                {zones.map((z) => {
                  const viols = activeViolations.filter(v => v.zoneName === z.name || v.id.includes(z.id));
                  return (
                    <tr key={z.id} className="hover:bg-slate-50 dark:hover:bg-slate-900/50">
                      <td className="px-3.5 py-2 font-semibold text-slate-900 dark:text-white">
                        {z.name}
                      </td>
                      <td className="px-3.5 py-2 text-slate-600 dark:text-slate-400 capitalize">
                        {z.type.replace('_', ' ')}
                      </td>
                      <td className="px-3.5 py-2">
                        {viols.length > 0 ? (
                          <span className="font-bold text-red-600 dark:text-red-400">{viols.length}</span>
                        ) : (
                          <span className="text-slate-500 dark:text-slate-400">0</span>
                        )}
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        </div>

        {/* Report Footer */}
        <div className="pt-4 border-t-2 border-slate-900 dark:border-white flex flex-col sm:flex-row sm:items-center justify-between text-[11px] text-slate-500 dark:text-slate-400">
          <div>
            Model: <strong className="text-slate-800 dark:text-slate-200">{modelConfig.name}</strong> | Tracker: <strong className="text-slate-800 dark:text-slate-200">{modelConfig.tracker}</strong>
          </div>
          <div className="font-bold tracking-wider uppercase text-slate-900 dark:text-white mt-1 sm:mt-0">
            REPORT GENERATED BY SECURECAM
          </div>
        </div>
      </div>
    </div>
  );
};
